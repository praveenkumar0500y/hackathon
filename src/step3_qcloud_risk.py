def compute_ece(y_true: np.ndarray, y_prob: np.ndarray, n_bins: int = 10) -> float:
    """Computes Expected Calibration Error (ECE) across uniform probability bins."""
    bin_boundaries = np.linspace(0.0, 1.0, n_bins + 1)
    ece = 0.0
    n = len(y_true)
    for i in range(n_bins):
        low, high = bin_boundaries[i], bin_boundaries[i + 1]
        in_bin = (y_prob >= low) & (y_prob <= high if i == n_bins - 1 else y_prob < high)
        n_b = np.sum(in_bin)
        if n_b > 0:
            acc = float(np.mean(y_true[in_bin]))
            conf = float(np.mean(y_prob[in_bin]))
            ece += (n_b / n) * abs(acc - conf)
    return float(ece)


def compute_bootstrap_ci(y_true: np.ndarray, y_prob: np.ndarray, metric_fn, n_boot: int = 500, seed: int = 42) -> Tuple[float, float]:
    """Computes 95% percentile bootstrap confidence interval for a metric."""
    rng = np.random.RandomState(seed)
    n = len(y_true)
    scores = []
    for _ in range(n_boot):
        idx = rng.randint(0, n, size=n)
        if len(np.unique(y_true[idx])) < 2:
            continue
        try:
            scores.append(metric_fn(y_true[idx], y_prob[idx]))
        except Exception:
            pass
    if not scores:
        val = metric_fn(y_true, y_prob)
        return float(val), float(val)
    return float(np.percentile(scores, 2.5)), float(np.percentile(scores, 97.5))


def build_circuit_variant_1(x: np.ndarray, scaling: float = 1.0, entangling: bool = True) -> qq.Circuit:
    """Variant 1: 1-Layer Angle Embedding (Ry, Rz) with optional CX Ring Entanglement."""
    c = qq.Circuit(3)
    for i in range(3):
        c.ry(i, float(scaling * 2.0 * np.pi * x[i]))
        c.rz(i, float(scaling * np.pi * x[i]))
    if entangling:
        c.cx(0, 1)
        c.cx(1, 2)
        c.cx(2, 0)
    return c


def build_kernel_circuit(x: np.ndarray, scaling: float = 1.0) -> qq.Circuit:
    """3-qubit ZZ feature map circuit for Quantum Kernel Classifier (QSVC)."""
    c = qq.Circuit(3)
    for i in range(3):
        c.h(i)
        c.rz(i, float(scaling * 2.0 * np.pi * x[i]))
    for i in range(2):
        c.cx(i, i + 1)
        c.rz(i + 1, float(scaling * 2.0 * (np.pi - x[i]) * (np.pi - x[i + 1])))
        c.cx(i, i + 1)
    c.cx(2, 0)
    c.rz(0, float(scaling * 2.0 * (np.pi - x[2]) * (np.pi - x[0])))
    c.cx(2, 0)
    return c


def build_circuit_variant_2(x: np.ndarray) -> qq.Circuit:
    """Variant 2: 2-Layer Data Re-Uploading with Alternating Entanglement."""
    c = qq.Circuit(3)
    # Layer 1
    for i in range(3):
        c.ry(i, float(2.0 * np.pi * x[i]))
        c.rz(i, float(np.pi * x[i]))
    c.cx(0, 1)
    c.cx(1, 2)
    c.cx(2, 0)
    # Layer 2 (Re-uploading with phase shifts)
    for i in range(3):
        c.rx(i, float(np.pi * (1.0 - x[i])))
        c.rz(i, float(2.0 * np.pi * x[i]))
    c.cx(2, 1)
    c.cx(1, 0)
    c.cx(0, 2)
    return c


def extract_features_from_probs(probs: np.ndarray) -> np.ndarray:
    """Computes local and correlated Pauli-Z expectation values from 8-state probabilities."""
    # <Z_0>: sum over basis states where bit 0 is 0 minus bit 0 is 1
    z0 = sum(probs[b] for b in range(8) if not (b & 1)) - sum(probs[b] for b in range(8) if (b & 1))
    z1 = sum(probs[b] for b in range(8) if not (b & 2)) - sum(probs[b] for b in range(8) if (b & 2))
    z2 = sum(probs[b] for b in range(8) if not (b & 4)) - sum(probs[b] for b in range(8) if (b & 4))
    
    # 2-qubit correlations
    z01 = sum(probs[b] for b in range(8) if bin(b & 3).count('1') % 2 == 0) - sum(probs[b] for b in range(8) if bin(b & 3).count('1') % 2 == 1)
    z12 = sum(probs[b] for b in range(8) if bin((b >> 1) & 3).count('1') % 2 == 0) - sum(probs[b] for b in range(8) if bin((b >> 1) & 3).count('1') % 2 == 1)
    
    # 3-qubit parity <Z0 Z1 Z2>
    parity = sum(probs[b] for b in range(8) if bin(b).count('1') % 2 == 0) - sum(probs[b] for b in range(8) if bin(b).count('1') % 2 == 1)

    return np.array([z0, z1, z2, z01, z12, parity], dtype=float)


def extract_quantum_features(statevector: list) -> np.ndarray:
    """Computes local and correlated Pauli-Z expectation values from statevector."""
    sv = np.array(statevector, dtype=complex)
    probs = np.abs(sv) ** 2
    return extract_features_from_probs(probs)


def extract_quantum_features_from_counts(counts: Dict[str, int], total_shots: int) -> np.ndarray:
    """
    Computes local and correlated Pauli-Z expectation values from shot counts.
    Bitstrings are formatted as q_{n-1} ... q_1 q_0 (little-endian qubit order).
    """
    if total_shots <= 0:
        return np.zeros(6, dtype=float)

    z0, z1, z2 = 0.0, 0.0, 0.0
    z01, z12 = 0.0, 0.0
    parity = 0.0

    for bitstring, count in counts.items():
        s = bitstring.zfill(3)
        b0 = 1 if s[-1] == '0' else -1  # Qubit 0
        b1 = 1 if s[-2] == '0' else -1  # Qubit 1
        b2 = 1 if s[-3] == '0' else -1  # Qubit 2

        z0 += b0 * count
        z1 += b1 * count
        z2 += b2 * count
        z01 += (b0 * b1) * count
        z12 += (b1 * b2) * count
        parity += (b0 * b1 * b2) * count

    return np.array([z0, z1, z2, z01, z12, parity], dtype=float) / total_shots


def apply_emulated_noise_channel(
    probs: np.ndarray,
    p_bitflip: float = 0.03,
    p_depol: float = 0.05
) -> np.ndarray:
    """
    Documented composite hardware noise emulation on 3-qubit measurement distributions:
    1. Global Depolarizing Channel:
       With probability p_depol, state collapses to maximally mixed state (1/8):
       p_mixed = (1 - p_depol) * probs + p_depol / 8.0
    2. Symmetric Single-Qubit Readout Error (Measurement Bit-Flip):
       Each qubit bit flips independently with probability p_bitflip:
       P(b_out | b_in) = (p_bitflip)^d * (1 - p_bitflip)^(3 - d), d = HammingDistance(b_in, b_out)
    """
    n_states = len(probs)
    mixed = (1.0 - p_depol) * probs + (p_depol / n_states)

    T = np.zeros((n_states, n_states), dtype=float)
    for b_in in range(n_states):
        for b_out in range(n_states):
            d = bin(b_in ^ b_out).count('1')
            T[b_out, b_in] = (p_bitflip ** d) * ((1.0 - p_bitflip) ** (3 - d))

    noisy_probs = T @ mixed
    return np.clip(noisy_probs / np.sum(noisy_probs), 0.0, 1.0)



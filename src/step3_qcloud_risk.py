def run_shot_sensitivity_study(
    unique_probs: Dict[tuple, np.ndarray],
    unique_to_indices: Dict[tuple, List[int]],
    y: np.ndarray,
    skf: StratifiedKFold,
    shot_levels: List[int] = [128, 1024, 8192],
    n_repeats: int = 20,
    base_seed: int = 4200
) -> Dict[str, Any]:
    """
    Shot-sampled mode: sample from circuit probabilities with shots in [128, 1024, 8192]
    and report how p_ij, AUC, and Brier change (mean +/- std over 20 repeats).
    """
    n_samples = len(y)
    results_by_shots = {}

    for shots in shot_levels:
        brier_runs = []
        auc_runs = []
        leg_p_runs = []

        for r in range(n_repeats):
            rng = np.random.RandomState(base_seed + r * 100 + shots)
            X_sampled = np.zeros((n_samples, 4))
            r_leg_probs = []

            for u_tuple, prob_dist in unique_probs.items():
                counts = rng.multinomial(shots, prob_dist)
                p_samp = counts / float(shots)
                f_full = extract_features_from_probs(p_samp)
                f4 = f_full[[0, 1, 2, 5]]
                for idx in unique_to_indices[u_tuple]:
                    X_sampled[idx] = f4

            oof_p = np.zeros(n_samples)
            for tr_idx, te_idx in skf.split(X_sampled, y):
                clf = LogisticRegression(C=1.0, max_iter=500)
                clf.fit(X_sampled[tr_idx], y[tr_idx])
                oof_p[te_idx] = clf.predict_proba(X_sampled[te_idx])[:, 1]

            brier = float(brier_score_loss(y, oof_p))
            auc = float(roc_auc_score(y, oof_p))
            brier_runs.append(round(brier, 4))
            auc_runs.append(round(auc, 4))

            for u_tuple in unique_probs:
                idxs = unique_to_indices[u_tuple]
                r_leg_probs.append(float(np.mean(oof_p[idxs])))
            leg_p_runs.append(r_leg_probs)

        leg_p_runs = np.array(leg_p_runs)
        leg_stds = np.std(leg_p_runs, axis=0)
        mean_leg_std = float(np.mean(leg_stds))
        mean_leg_var = float(np.mean(np.var(leg_p_runs, axis=0)))

        results_by_shots[str(shots)] = {
            "shots": shots,
            "n_repeats": n_repeats,
            "brier_mean": round(float(np.mean(brier_runs)), 4),
            "brier_std": round(float(np.std(brier_runs)), 4),
            "brier_ci_95": [round(float(np.percentile(brier_runs, 2.5)), 4), round(float(np.percentile(brier_runs, 97.5)), 4)],
            "brier_95_ci": [round(float(np.percentile(brier_runs, 2.5)), 4), round(float(np.percentile(brier_runs, 97.5)), 4)],
            "roc_auc_mean": round(float(np.mean(auc_runs)), 4),
            "roc_auc_std": round(float(np.std(auc_runs)), 4),
            "roc_auc_ci_95": [round(float(np.percentile(auc_runs, 2.5)), 4), round(float(np.percentile(auc_runs, 97.5)), 4)],
            "roc_auc_95_ci": [round(float(np.percentile(auc_runs, 2.5)), 4), round(float(np.percentile(auc_runs, 97.5)), 4)],
            "mean_p_ij_std_across_legs": round(mean_leg_std, 4),
            "mean_p_ij_variance_across_legs": round(mean_leg_var, 6),
            "repeats_brier": brier_runs,
            "repeats_roc_auc": auc_runs
        }

    return results_by_shots


def run_noise_degradation_study(
    unique_probs: Dict[tuple, np.ndarray],
    unique_to_indices: Dict[tuple, List[int]],
    y: np.ndarray,
    skf: StratifiedKFold,
    noise_levels: List[float] = [0.00, 0.01, 0.03, 0.05, 0.10],
    eval_shots: int = 1024,
    seed: int = 4242
) -> Dict[str, Any]:
    """
    Evaluates circuit degradation under emulated depolarizing and readout bit-flip noise channels.
    """
    n_samples = len(y)
    results_by_noise = {}
    baseline_brier = None

    for eps in noise_levels:
        rng = np.random.RandomState(seed + int(eps * 1000))
        X_noisy = np.zeros((n_samples, 4))

        for u_tuple, prob_dist in unique_probs.items():
            if eps > 0:
                p_dist_noisy = apply_emulated_noise_channel(prob_dist, p_bitflip=eps, p_depol=2.0 * eps)
            else:
                p_dist_noisy = prob_dist

            counts = rng.multinomial(eval_shots, p_dist_noisy)
            p_samp = counts / float(eval_shots)
            f_full = extract_features_from_probs(p_samp)
            f4 = f_full[[0, 1, 2, 5]]
            for idx in unique_to_indices[u_tuple]:
                X_noisy[idx] = f4

        oof_p = np.zeros(n_samples)
        for tr_idx, te_idx in skf.split(X_noisy, y):
            clf = LogisticRegression(C=1.0, max_iter=500)
            clf.fit(X_noisy[tr_idx], y[tr_idx])
            oof_p[te_idx] = clf.predict_proba(X_noisy[te_idx])[:, 1]

        preds = (oof_p >= 0.5).astype(int)
        brier = float(brier_score_loss(y, oof_p))
        auc = float(roc_auc_score(y, oof_p))
        acc = float(accuracy_score(y, preds))

        if baseline_brier is None:
            baseline_brier = brier
            degradation_pct = 0.0
        else:
            degradation_pct = round(((brier - baseline_brier) / baseline_brier) * 100.0, 2)

        results_by_noise[f"eps_{eps:.2f}"] = {
            "epsilon_readout_bitflip": eps,
            "lambda_depolarizing": round(2.0 * eps, 4),
            "brier_score": round(brier, 4),
            "roc_auc": round(auc, 4),
            "accuracy": round(acc, 4),
            "brier_degradation_pct": degradation_pct
        }

    return results_by_noise


def run_fair_model_benchmarks(
    X_raw: np.ndarray,
    X_q: np.ndarray,
    X_hybrid: np.ndarray,
    K_full: np.ndarray,
    y: np.ndarray,
    rskf: RepeatedStratifiedKFold
) -> Dict[str, Any]:
    """
    Evaluates 5 models on identical repeated stratified CV folds with equivalent tuning budget:
    1. Classical Logistic Regression (Raw)
    2. Classical Gradient Boosting (Raw)
    3. Quantum Features Logistic Regression
    4. Hybrid Raw + Quantum Logistic Regression
    5. Quantum Kernel SVC (QSVC with Platt scaling)
    """
    models_config = {
        "Classical_Logistic_Regression_Raw": {
            "type": "linear",
            "X": X_raw,
            "param_grid": {"C": [0.01, 0.1, 1.0, 10.0]}
        },
        "Classical_Gradient_Boosting_Raw": {
            "type": "gb",
            "X": X_raw,
            "param_grid": {"n_estimators": [30, 50], "max_depth": [2, 3], "learning_rate": [0.05, 0.1]}
        },
        "Quantum_Features_Logistic_Regression": {
            "type": "linear",
            "X": X_q,
            "param_grid": {"C": [0.01, 0.1, 1.0, 10.0]}
        },
        "Hybrid_Raw_Plus_Quantum_Logistic_Regression": {
            "type": "linear",
            "X": X_hybrid,
            "param_grid": {"C": [0.01, 0.1, 1.0, 10.0]}
        },
        "Quantum_Kernel_SVC": {
            "type": "qsvc",
            "K": K_full,
            "param_grid": {"C": [0.1, 1.0, 10.0]}
        }
    }

    benchmark_results = {}

    for m_name, cfg in models_config.items():
        fold_briers = []
        fold_aucs = []
        fold_loglosses = []
        fold_eces = []

        for train_idx, test_idx in rskf.split(X_raw, y):
            y_tr, y_te = y[train_idx], y[test_idx]

            if cfg["type"] == "linear":
                X_tr, X_te = cfg["X"][train_idx], cfg["X"][test_idx]
                grid = GridSearchCV(LogisticRegression(max_iter=500), cfg["param_grid"], cv=3, scoring="neg_brier_score")
                grid.fit(X_tr, y_tr)
                best_model = grid.best_estimator_
                p_te = best_model.predict_proba(X_te)[:, 1]

            elif cfg["type"] == "gb":
                X_tr, X_te = cfg["X"][train_idx], cfg["X"][test_idx]
                grid = GridSearchCV(GradientBoostingClassifier(random_state=42), cfg["param_grid"], cv=3, scoring="neg_brier_score")
                grid.fit(X_tr, y_tr)
                best_model = grid.best_estimator_
                p_te = best_model.predict_proba(X_te)[:, 1]

            elif cfg["type"] == "qsvc":
                K_tr = cfg["K"][np.ix_(train_idx, train_idx)]
                K_te = cfg["K"][np.ix_(test_idx, train_idx)]
                best_c = 1.0
                best_sc = -999.0
                for c_cand in cfg["param_grid"]["C"]:
                    sub_svc = SVC(kernel="precomputed", C=c_cand)
                    sub_svc.fit(K_tr[:1500, :1500], y_tr[:1500])
                    sc = float(np.mean(sub_svc.predict(K_tr[1500:, :1500]) == y_tr[1500:]))
                    if sc > best_sc:
                        best_sc = sc
                        best_c = c_cand

                svc = SVC(kernel="precomputed", C=best_c)
                svc.fit(K_tr, y_tr)
                df_tr = svc.decision_function(K_tr).reshape(-1, 1)
                df_te = svc.decision_function(K_te).reshape(-1, 1)
                platt = LogisticRegression(C=1.0, max_iter=500)
                platt.fit(df_tr, y_tr)
                p_te = platt.predict_proba(df_te)[:, 1]

            fold_briers.append(brier_score_loss(y_te, p_te))
            fold_aucs.append(roc_auc_score(y_te, p_te))
            fold_loglosses.append(log_loss(y_te, p_te))
            fold_eces.append(compute_ece(y_te, p_te))

        benchmark_results[m_name] = {
            "brier_mean": round(float(np.mean(fold_briers)), 4),
            "brier_std": round(float(np.std(fold_briers)), 4),
            "auc_mean": round(float(np.mean(fold_aucs)), 4),
            "auc_std": round(float(np.std(fold_aucs)), 4),
            "log_loss_mean": round(float(np.mean(fold_loglosses)), 4),
            "log_loss_std": round(float(np.std(fold_loglosses)), 4),
            "ece_mean": round(float(np.mean(fold_eces)), 4),
            "ece_std": round(float(np.std(fold_eces)), 4),
            "n_folds_evaluated": len(fold_briers)
        }

    return benchmark_results


def run_ablation_study(
    unique_tuples: List[tuple],
    X_raw: np.ndarray,
    y: np.ndarray,
    rskf: RepeatedStratifiedKFold,
    sim: StatevectorSimulator
) -> Dict[str, Any]:
    """
    Ablation study on identical folds:
    - With vs without entangling gates
    - Angle feature scalings in [0.5, 1.0, 2.0]
    """
    scalings = [0.5, 1.0, 2.0]
    entanglements = [True, False]
    ablation_results = {}

    for ent in entanglements:
        for sc in scalings:
            tag = f"{'With_Entanglement' if ent else 'Without_Entanglement'}_scale_{sc:.1f}"
            cache_abl = {}
            for u in unique_tuples:
                c_abl = build_circuit_variant_1(np.array(u), scaling=sc, entangling=ent)
                p_abl = np.abs(np.array(sim.run(c_abl).statevector)) ** 2
                cache_abl[u] = extract_features_from_probs(p_abl)[[0, 1, 2, 5]]
            X_abl = np.array([cache_abl[tuple(np.round(x, 4))] for x in X_raw])

            b_list, a_list, l_list, e_list = [], [], [], []
            for train_idx, test_idx in rskf.split(X_raw, y):
                y_tr, y_te = y[train_idx], y[test_idx]
                grid = GridSearchCV(LogisticRegression(max_iter=500), {"C": [0.01, 0.1, 1.0, 10.0]}, cv=3, scoring="neg_brier_score")
                grid.fit(X_abl[train_idx], y_tr)
                best_model = grid.best_estimator_
                p_te = best_model.predict_proba(X_abl[test_idx])[:, 1]
                b_list.append(brier_score_loss(y_te, p_te))
                a_list.append(roc_auc_score(y_te, p_te))
                l_list.append(log_loss(y_te, p_te))
                e_list.append(compute_ece(y_te, p_te))

            ablation_results[tag] = {
                "has_entanglement": ent,
                "angle_scaling": sc,
                "brier_mean": round(float(np.mean(b_list)), 4),
                "brier_std": round(float(np.std(b_list)), 4),
                "auc_mean": round(float(np.mean(a_list)), 4),
                "auc_std": round(float(np.std(a_list)), 4),
                "log_loss_mean": round(float(np.mean(l_list)), 4),
                "log_loss_std": round(float(np.std(l_list)), 4),
                "ece_mean": round(float(np.mean(e_list)), 4),
                "ece_std": round(float(np.std(e_list)), 4),
                "n_folds_evaluated": len(b_list)
            }

    return ablation_results


